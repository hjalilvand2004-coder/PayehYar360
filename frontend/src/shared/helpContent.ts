/** موضوع راهنما بر اساس مسیر صفحه — برای صفحات جزئیات هم پیشوندی کار می‌کند. */
export function helpTopicForPath(path: string): string | null {
  const p = (path || '/').split('?')[0].replace(/\/+$/, '') || '/'
  if (p === '/') return 'dashboard'
  if (p.startsWith('/persons')) return 'persons'
  if (p.startsWith('/organizations')) return 'organizations'
  if (p.startsWith('/references')) return 'references'
  if (p.startsWith('/instructors')) return 'instructors'
  if (p.startsWith('/classrooms')) return 'classrooms'
  if (p.startsWith('/services')) return 'services'
  if (p.startsWith('/mappings')) return 'mappings'
  if (p.startsWith('/ownership')) return 'ownership'
  if (p.startsWith('/quality')) return 'quality'
  if (p.startsWith('/change-requests')) return 'changeRequests'
  if (p.startsWith('/integrations')) return 'integrations'
  if (p.startsWith('/audit')) return 'audit'
  return null
}
